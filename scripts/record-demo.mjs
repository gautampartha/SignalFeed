import { chromium } from '@playwright/test';
import { mkdir, readFile, rename } from 'node:fs/promises';

await mkdir('demo', {recursive:true});
const browser=await chromium.launch({channel:'chrome'});
// Rasterize our code-native vector app icon for the iOS asset catalogue.
const iconPage=await browser.newPage({viewport:{width:1024,height:1024},deviceScaleFactor:1});
const svg=await readFile('app/icon.svg','utf8');
await iconPage.setContent(`<style>*{margin:0}svg{width:1024px;height:1024px;display:block;background:#124e3d}</style>${svg}`);
await iconPage.screenshot({path:'ios/App/App/Assets.xcassets/AppIcon.appiconset/AppIcon-512@2x.png'});
await iconPage.close();

const context=await browser.newContext({viewport:{width:1440,height:1050},recordVideo:{dir:'demo/.recording',size:{width:1440,height:1050}}});
const page=await context.newPage();
const video=page.video();
await page.goto('http://localhost:5180/');
await page.evaluate(()=>localStorage.clear());
await page.reload();
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:'demo/desktop-signalfeed.png',fullPage:true});
await page.waitForTimeout(1700);
await page.locator('.launch-demo').click();
await page.waitForTimeout(3500);
const next=page.locator('#demo-panel [data-action="demo-next"]');
await next.click();
await page.waitForTimeout(4500);
await next.click();
await page.waitForTimeout(5500);
await page.locator('[data-action="detail"][data-id="forma"]').scrollIntoViewIfNeeded();
await page.waitForTimeout(3500);
await page.screenshot({path:'demo/internship-card.png',fullPage:true});
await page.locator('[data-action="detail"][data-id="forma"]').click();
await page.waitForTimeout(4000);
await page.locator('[data-action="close"]').click();
await next.click();
await page.waitForTimeout(3500);
await next.click();
await page.waitForTimeout(4000);
await page.locator('[data-action="confirm-reminder"]').click();
await page.waitForTimeout(4000);
await page.screenshot({path:'demo/reminder-confirmation.png',fullPage:true});
await page.locator('[data-action="show-reminders"]').click();
await page.waitForTimeout(3000);
await next.click();
await page.waitForTimeout(2000);
await context.close();
await rename(await video.path(),'demo/internship-demo.webm');
await browser.close();
console.log('Created demo/internship-demo.webm, screenshots, and the native app icon.');
